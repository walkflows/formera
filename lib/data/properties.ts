export function neighbourhoodCount(neighbourhood: string): number {
  return properties.filter((p) => p.neighbourhood === neighbourhood).length;
}

export function getRelatedProperties(current: Property, max = 3): Property[] {
  const candidates = properties.filter(
    (p) => p.id !== current.id && p.purpose === current.purpose
  );

  const score = (p: Property) => {
    let s = 0;
    if (p.neighbourhood === current.neighbourhood) s += 100;
    if (p.type === current.type) s += 10;
    s -= Math.abs(p.price - current.price) / current.price;
    return s;
  };

  return candidates.sort((a, b) => score(b) - score(a)).slice(0, max);
}
